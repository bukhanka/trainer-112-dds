/**
 * Tickets worked through by hand: how the caller talks, what they know only when asked,
 * and the reference for the duty services (ДДС): first decision within 30 s, the status
 * chain the brigade reports make possible, what the final comment must contain, traps.
 * Every ticket listed here becomes APPROVED in data/scenarios.json.
 * Status names follow the ServiceStatus enum of prisma/schema.prisma.
 */
import type { Temper } from "./tickets";

export type DdsStatus = "ACCEPTED" | "REJECTED" | "STARTED" | "ARRIVED" | "WORKING" | "FINISHED" | "REFUSED";

export type DdsServiceReference = {
  service: string; // plate short name, resolved to serviceId by the builder
  decision: "ACCEPTED" | "REJECTED";
  /** mandatory for «Не принята»: reason and to whom it was passed */
  decisionComment?: string;
  chain: DdsStatus[];
  /** what the brigade leader reports by phone — the facts for the comments */
  brigadeReport: string;
  commentMustHave: string[];
  traps: string[];
};

export type DeepScenario = {
  situation: string;
  facts: string[];
  temper?: Temper;
  questions?: string[];
  dds: DdsServiceReference[];
  notes?: string;
};

